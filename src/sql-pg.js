// Postgres 轉接用的 SQL 轉譯（純函式）：業務程式照寫 SQLite／D1 的 SQL，連 Postgres 時在這裡換成 Postgres 寫法。
// 只改字串常值與註解以外的部分。查詢（queryToPg）與建表（ddlToPg）分開：
//   查詢：? → $1…、IN (SELECT value FROM json_each(?)) → = ANY($n)（參數改成陣列）、FROM json_each(?) → json_array_elements、INSERT OR IGNORE → ON CONFLICT DO NOTHING、instr → strpos、json_valid、
//         LIKE → ILIKE（SQLite 的 LIKE 本來就不分英文大小寫）、索引提示 +欄位 拿掉、CAST(… AS INTEGER) → BIGINT、PRAGMA table_info
//   建表：INTEGER → BIGINT（毫秒時間戳記超過 int4）、AUTOINCREMENT → IDENTITY、BLOB → BYTEA、
//         TEXT 用 "C" 排序（跟 SQLite 一樣逐位元組比較）、COLLATE NOCASE → 不分大小寫的 nocase 排序規則、
//         每張表加隱藏的 rowid 流水號（通知排序、備份分頁會用到；查詢結果由轉接層拿掉）

// 把 SQL 切成「程式碼」與「字串、識別字、註解」兩種片段，只把程式碼片段交給 fn 改
export function mapCode(sql, fn) {
  let out = '', code = '', i = 0;
  const flush = () => { if (code) { out += fn(code); code = ''; } };
  while (i < sql.length) {
    const c = sql[i];
    if (c === "'" || c === '"') {
      flush();
      let j = i + 1;
      for (;;) {
        if (j >= sql.length) break;
        if (sql[j] === c) { if (sql[j + 1] === c) { j += 2; continue; } break; }
        j++;
      }
      out += sql.slice(i, j + 1); i = j + 1;
    } else if (c === '-' && sql[i + 1] === '-') {
      flush();
      const j = sql.indexOf('\n', i);
      const end = j < 0 ? sql.length : j;
      out += sql.slice(i, end); i = end;
    } else { code += c; i++; }
  }
  flush();
  return out;
}

// 依分號切成一句一句（字串與註解裡的分號不算）
export function splitStatements(sql) {
  const marked = mapCode(sql, code => code.replace(/;/g, '\u0000'));
  return marked.split('\u0000').map(s => s.trim()).filter(s => s && mapCode(s, c => c).replace(/--[^\n]*/g, '').trim());
}

const pragmaInfo = t => `SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '${t}' AND column_name <> 'rowid' ORDER BY ordinal_position`;

// 查詢：回傳 { text, arrays }；arrays＝要從 JSON 字串轉成陣列的參數位置（從 0 起）
export function queryToPg(sql) {
  const pragma = /^\s*PRAGMA\s+table_info\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)\s*;?\s*$/i.exec(sql);
  if (pragma) return { text: pragmaInfo(pragma[1]), arrays: [] };
  let n = 0;
  const arrays = [];
  let orIgnore = false;
  // json_extract(欄位, '$.key') → (欄位::json ->> 'key')（路徑在字串常值裡，先整句換）
  sql = sql.replace(/\bjson_extract\(\s*([A-Za-z_][\w.]*)\s*,\s*'\$\.([A-Za-z_]\w*)'\s*\)/g, "($1::json ->> '$2')");
  let text = mapCode(sql, code => code
    .replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/gi, () => { orIgnore = true; return 'INSERT INTO'; })
    .replace(/\b(NOT\s+)?IN\s*\(\s*SELECT\s+value\s+FROM\s+json_each\(\s*\?\s*\)\s*\)|\bFROM\s+json_each\(\s*\?\s*\)|\?/gi, (m, not) => {
      if (m === '?') return '$' + ++n;
      if (/^FROM/i.test(m)) return `FROM json_array_elements($${++n}::json) AS j(value)`; // 一次插入多列：INSERT … SELECT … FROM json_each(?)
      arrays.push(n); return (not ? '<> ALL($' : '= ANY($') + ++n + ')';
    })
    .replace(/\bLIKE\b/gi, 'ILIKE')
    .replace(/\binstr\(/gi, 'strpos(') // 一樣從 1 起算、找不到回 0
    .replace(/\bjson_valid\(([^()]*)\)/gi, "pg_input_is_valid($1, 'json')") // Postgres 16 以上
    .replace(/\b(AND|OR|WHERE|ON)(\s+)\+(?=[A-Za-z_])/gi, '$1$2')
    .replace(/\bAS\s+INTEGER\s*\)/gi, 'AS BIGINT)'));
  if (orIgnore) text = appendOnConflict(text);
  return { text, arrays };
}

// INSERT OR IGNORE：句尾（RETURNING 前）補 ON CONFLICT DO NOTHING
function appendOnConflict(stmt) {
  const body = stmt.replace(/;\s*$/, '');
  const marked = mapCode(body, code => code.replace(/\bRETURNING\b/gi, '\u0001RETURNING'));
  const at = marked.indexOf('\u0001');
  if (at < 0) return body + ' ON CONFLICT DO NOTHING';
  return marked.slice(0, at) + 'ON CONFLICT DO NOTHING ' + marked.slice(at + 1);
}

// 建表（schema.sql、migrations/*.sql）：回傳 Postgres 可以直接執行的多句 SQL
export const NOCASE_COLLATION = "CREATE COLLATION IF NOT EXISTS nocase (provider = icu, locale = 'und-u-ks-level2', deterministic = false)";
export function ddlToPg(sql) {
  return splitStatements(sql).map(stmt => {
    // 型別只認大寫（schema.sql 的慣例）：欄位名稱 text、size 這類小寫的不會被當成型別
    let s = mapCode(stmt, code => code
      .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      .replace(/\bINTEGER\b/g, 'BIGINT')
      .replace(/\bBLOB\b/g, 'BYTEA')
      .replace(/\bTEXT\b([^,()]*?)\s+COLLATE\s+NOCASE\b/g, 'TEXT COLLATE nocase$1')
      .replace(/\bTEXT\b(?!\s+COLLATE)/g, 'TEXT COLLATE "C"'));
    if (/^\s*CREATE\s+TABLE\b/i.test(stripComments(s))) s = s.replace(/(CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[A-Za-z_]\w*\s*)\(/i, '$1(\n  rowid BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,');
    if (/^\s*INSERT\s+OR\s+IGNORE\b/i.test(stripComments(s))) s = queryToPg(s).text;
    return s;
  }).map(s => s + ';').join('\n');
}
const stripComments = s => s.replace(/--[^\n]*\n?/g, '').trimStart();

// 純函式：資料表與欄位名稱（測試用來比對 SQLite 版與 Postgres 版對得上）
export function tablesOf(sql) {
  const out = new Map();
  for (const stmt of splitStatements(sql)) {
    const s = stripComments(stmt);
    const m = /^CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_]\w*)\s*\(([\s\S]*)\)\s*$/i.exec(s);
    if (m) {
      const cols = [];
      for (const line of m[2].replace(/--[^\n]*/g, '').split(/,(?![^(]*\))/)) {
        const w = /^\s*([A-Za-z_]\w*)\s+/.exec(line);
        if (w && !/^(PRIMARY|UNIQUE|FOREIGN|CHECK|CONSTRAINT)$/i.test(w[1])) cols.push(w[1]);
      }
      out.set(m[1], cols);
      continue;
    }
    const a = /^ALTER\s+TABLE\s+([A-Za-z_]\w*)\s+ADD\s+COLUMN\s+([A-Za-z_]\w*)/i.exec(s);
    if (a) out.set(a[1], [...(out.get(a[1]) || []), a[2]]);
  }
  return out;
}
