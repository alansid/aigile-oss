// PLAT-369 Postgres 轉接：SQL 轉譯（純函式）＋ SQLite 版與 Postgres 版的資料表對得上
// 1. 查詢轉譯：? → $n（字串裡的不動）、json_each → ANY／ALL（參數改陣列）、INSERT OR IGNORE、LIKE、索引提示、PRAGMA、json_extract
// 2. 建表轉譯：型別、AUTOINCREMENT、NOCASE、每張表加隱藏 rowid；欄位叫 text 的不會被當成型別
// 3. migrations/pg/ 的取代檔都要對到 migrations/ 的同名檔
// 4. 有 AIGILE_TEST_PG_URL（只准本機）時：實際建表，逐表比對 SQLite 與 Postgres 的欄位；再模擬舊站，確認升級會補套
// 用法：node scripts/sql-pg-test.js（AIGILE_TEST_PG_URL=postgres://…@127.0.0.1/… 另外跑實機比對）
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { queryToPg, ddlToPg, splitStatements, tablesOf } from '../src/sql-pg.js';
import { listMigrations } from '../src/migrations.js';
import { openNodeDb } from '../src/db-node.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const schema = fs.readFileSync(path.join(root, 'src', 'schema.sql'), 'utf8');

// 1. 查詢
{
  assert.deepEqual(queryToPg('SELECT * FROM t WHERE a = ? AND b = ?'), { text: 'SELECT * FROM t WHERE a = $1 AND b = $2', arrays: [] });
  assert.equal(queryToPg("SELECT '?' AS q, x FROM t WHERE y = ?").text, "SELECT '?' AS q, x FROM t WHERE y = $1", '字串裡的 ? 不動');
  assert.equal(queryToPg("SELECT 1 FROM t WHERE a = ? -- 註解裡的 ?\n AND b = ?").text, "SELECT 1 FROM t WHERE a = $1 -- 註解裡的 ?\n AND b = $2", '註解裡的 ? 不動');
  const je = queryToPg('SELECT * FROM t WHERE a = ? AND id IN (SELECT value FROM json_each(?)) AND b NOT IN (SELECT value FROM json_each(?)) LIMIT ?');
  assert.equal(je.text, 'SELECT * FROM t WHERE a = $1 AND id = ANY($2) AND b <> ALL($3) LIMIT $4');
  assert.deepEqual(je.arrays, [1, 2], 'json_each 的參數位置（從 0 起）');
  assert.equal(queryToPg('INSERT OR IGNORE INTO t (a) VALUES (?)').text, 'INSERT INTO t (a) VALUES ($1) ON CONFLICT DO NOTHING');
  assert.equal(queryToPg('INSERT OR IGNORE INTO t (a) VALUES (?) RETURNING a').text, 'INSERT INTO t (a) VALUES ($1) ON CONFLICT DO NOTHING RETURNING a');
  assert.equal(queryToPg("SELECT 1 FROM t WHERE x LIKE ? AND y NOT LIKE 'LIKE%'").text, "SELECT 1 FROM t WHERE x ILIKE $1 AND y NOT ILIKE 'LIKE%'", 'LIKE 不分大小寫（跟 SQLite 一樣），字串裡的不動');
  assert.equal(queryToPg('SELECT id FROM m WHERE id = ? AND +author_id = ?').text, 'SELECT id FROM m WHERE id = $1 AND author_id = $2', '索引提示 + 拿掉');
  assert.equal(queryToPg('SELECT a + b FROM t').text, 'SELECT a + b FROM t', '一般的加號不動');
  assert.equal(queryToPg("SELECT CAST(value AS INTEGER) FROM s").text, 'SELECT CAST(value AS BIGINT) FROM s');
  assert.match(queryToPg('PRAGMA table_info(cards)').text, /information_schema\.columns[\s\S]*table_name = 'cards'[\s\S]*column_name <> 'rowid'/);
  assert.equal(queryToPg("SELECT json_extract(s.payload, '$.project') FROM s").text, "SELECT (s.payload::json ->> 'project') FROM s");
  assert.equal(queryToPg("SELECT instr(files, 'x') FROM s WHERE json_valid(payload)").text, "SELECT strpos(files, 'x') FROM s WHERE pg_input_is_valid(payload, 'json')", 'instr、json_valid');
  assert.equal(queryToPg("SELECT 'it''s ?' FROM t WHERE a = ?").text, "SELECT 'it''s ?' FROM t WHERE a = $1", "字串裡的 '' 跳脫");
}

// 2. 建表
{
  const pg = ddlToPg(schema);
  assert.match(pg, /CREATE TABLE IF NOT EXISTS messages \(\n  rowid BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,\n  seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,/, 'AUTOINCREMENT → IDENTITY，加隱藏 rowid');
  assert.match(pg, /\n  text TEXT COLLATE "C" NOT NULL,/, '欄位名稱 text 不會被當成型別');
  assert.match(pg, /name TEXT COLLATE nocase NOT NULL UNIQUE,/, 'COLLATE NOCASE 移到型別後面');
  assert.match(pg, /data BYTEA NOT NULL/);
  assert.doesNotMatch(pg.replace(/--[^\n]*/g, ''), /\bINTEGER\b|\bBLOB\b|AUTOINCREMENT|INSERT OR IGNORE/, '沒有 SQLite 專用寫法留下');
  assert.match(pg, /INSERT INTO app_settings \(key, value\) VALUES \('isolation_since', '1970-01-01T00:00:00.000Z'\) ON CONFLICT DO NOTHING;/);
  assert.equal(splitStatements("A 'x;y'; -- z;\nB;").length, 2, '字串、註解裡的分號不切');
  // 兩邊的表與欄位：Postgres 版是從同一份 schema.sql 轉出來的，只多 rowid
  const lite = tablesOf(schema), pgT = tablesOf(pg);
  assert.deepEqual([...pgT.keys()].sort(), [...lite.keys()].sort(), '表一樣');
  for (const [t, cols] of lite) assert.deepEqual(pgT.get(t).filter(c => c !== 'rowid'), cols, `${t} 欄位一樣`);
  // 升級檔也轉得過去
  for (const f of listMigrations(path.join(root, 'migrations'))) assert.doesNotMatch(ddlToPg(f.sql).replace(/--[^\n]*/g, ''), /\bINTEGER\b|\bBLOB\b/, `${f.name} 轉得過去`);
}

// 3. migrations/pg/ 的取代檔（轉不過去才寫）要對到同名的升級檔
{
  const dir = path.join(root, 'migrations', 'pg');
  const names = new Set(listMigrations(path.join(root, 'migrations')).map(f => f.name));
  if (fs.existsSync(dir)) for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.sql'))) assert.ok(names.has(f), `migrations/pg/${f} 沒有對應的 migrations/${f}`);
}

// 4. 實機（只准本機）：兩邊實際的表與欄位、舊站升級
const PG_URL = process.env.AIGILE_TEST_PG_URL;
if (PG_URL) {
  const { openPgDb, assertTestPgUrl, testSchemaFor } = await import('../src/db-pg.js');
  const { default: pg } = await import('pg');
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'aigile-sqlpg-'));
  const lite = openNodeDb(path.join(tmp, 'a.db'), { legacyProjects: false });
  const sch = testSchemaFor(path.join(tmp, 'pg'));
  const db = await openPgDb(assertTestPgUrl(PG_URL), { legacyProjects: false, schema: sch, max: 2 });
  try {
    const liteTables = (await lite.all("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name")).map(r => r.name);
    const pgTables = (await db.all("SELECT table_name AS name FROM information_schema.tables WHERE table_schema = current_schema() ORDER BY table_name")).map(r => r.name);
    assert.deepEqual(pgTables, liteTables, 'Postgres 與 SQLite 的表一樣');
    for (const t of liteTables) {
      const a = (await lite.all(`PRAGMA table_info(${t})`)).map(c => c.name).sort();
      const b = (await db.all(`PRAGMA table_info(${t})`)).map(c => c.name).sort();
      assert.deepEqual(b, a, `${t} 的欄位一樣`);
    }
    assert.deepEqual((await db.all('SELECT name FROM schema_migrations ORDER BY name')).map(r => r.name), (await lite.all('SELECT name FROM schema_migrations ORDER BY name')).map(r => r.name), '升級紀錄一樣');
    // 名字不分大小寫（SQLite 的 COLLATE NOCASE）：查得到、也不能重複
    await db.run("INSERT INTO participants (id, kind, name, code, token, created_at, updated_at) VALUES ('p1', 'human', 'Amy', 'A1', 'h:1', 't', 't')");
    assert.equal((await db.get('SELECT id FROM participants WHERE name = ?', 'AMY'))?.id, 'p1', '名字查詢不分大小寫');
    await assert.rejects(db.run("INSERT INTO participants (id, kind, name, code, token, created_at, updated_at) VALUES ('p2', 'human', 'amy', 'A2', 'h:2', 't', 't')"), /duplicate|unique/i, '大小寫不同也算同名');
    // 型別跟 node:sqlite 一樣：COUNT → Number、BLOB → Uint8Array、* 不帶 rowid
    assert.equal(typeof (await db.get('SELECT COUNT(*) AS n FROM participants')).n, 'number');
    await db.run("INSERT INTO avatars (participant_id, mime, data, updated_at) VALUES (?, 'image/png', ?, 't')", 'p1', new Uint8Array([1, 2, 3]));
    const av = await db.get('SELECT * FROM avatars WHERE participant_id = ?', 'p1');
    assert.ok(av.data instanceof Uint8Array && [...av.data].join() === '1,2,3', 'BLOB 讀回 Uint8Array');
    assert.ok(!('rowid' in av), '* 不帶隱藏的 rowid');
    // 交易：一句失敗整批回復
    await assert.rejects(db.batch([["INSERT INTO app_settings (key, value) VALUES ('k1', 'v')", []], ["INSERT INTO app_settings (key, value) VALUES ('k1', 'v')", []]]));
    assert.equal(await db.get("SELECT * FROM app_settings WHERE key = 'k1'"), null, '整批回復');
  } finally { await db.close(); await lite.close(); }

  // 舊站：拿掉 002 的三個欄位與紀錄，重開要補套 002
  const c = new pg.Client({ connectionString: PG_URL, options: `-c search_path=${sch}` });
  await c.connect();
  await c.query("ALTER TABLE participants DROP COLUMN wake_day, DROP COLUMN wake_count, DROP COLUMN wake_at; DELETE FROM schema_migrations WHERE name = '002_wake_counts.sql'");
  await c.end();
  const logs = [], log = console.log;
  console.log = (...a) => logs.push(a.join(' '));
  const again = await openPgDb(PG_URL, { legacyProjects: false, schema: sch, max: 1 }).finally(() => { console.log = log; });
  try {
    assert.ok(logs.some(l => l.includes('002_wake_counts.sql')), '舊站重開會補套升級：' + logs.join(' / '));
    assert.equal((await again.get("SELECT wake_count FROM participants WHERE id = 'p1'")).wake_count, 0, '補回欄位、預設值');
  } finally { await again.close(); }
  // 資料庫比程式新（有程式不認得的升級）：拒絕啟動
  const c2 = new pg.Client({ connectionString: PG_URL, options: `-c search_path=${sch}` });
  await c2.connect(); await c2.query("INSERT INTO schema_migrations (name, applied_at) VALUES ('999_future.sql', 't')"); await c2.end();
  await assert.rejects(openPgDb(PG_URL, { legacyProjects: false, schema: sch, max: 1 }), e => e.name === 'MigrationError' && e.message.includes('999_future.sql'));
  fs.rmSync(tmp, { recursive: true, force: true });
  console.log('sql-pg-test：全部通過（含 Postgres 實機比對）');
} else {
  console.log('sql-pg-test：全部通過（沒設 AIGILE_TEST_PG_URL，略過 Postgres 實機比對）');
}
